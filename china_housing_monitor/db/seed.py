def seed_nbs_from_csv(conn, csv_path):
    """Import NBS price index data from CSV for new cities (v0.8)."""
    import csv
    import os
    
    # City name to city_id mapping for new 16 cities
    CITY_NAME_TO_ID = {
        '石家庄': 'sjz', '太原': 'ty', '呼和浩特': 'hhht',
        '沈阳': 'sy', '长春': 'cc', '哈尔滨': 'heb',
        '南昌': 'nc', '济南': 'jn', '南宁': 'nn',
        '海口': 'hk', '贵阳': 'gy', '昆明': 'km',
        '兰州': 'lz', '西宁': 'xn', '银川': 'yc',
        '乌鲁木齐': 'wlmq'
    }
    
    if not os.path.exists(csv_path):
        print(f'CSV file not found: {csv_path}')
        return 0
    
    cursor = conn.cursor()
    rows_imported = 0
    
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.reader(f)
        header = next(reader)  # Skip header
        
        for row in reader:
            month = row[0]
            city_name = row[1]
            
            # Only import for new 16 cities
            if city_name not in CITY_NAME_TO_ID:
                continue
            
            city_id = CITY_NAME_TO_ID[city_name]
            
            # Parse values: 新建住宅环比, 新建住宅同比, 二手住宅环比, 二手住宅同比
            try:
                new_home_mom = float(row[2])
                new_home_yoy = float(row[3])
                resale_home_mom = float(row[4])
                resale_home_yoy = float(row[5])
            except (ValueError, IndexError):
                continue
            
            # Insert into city_price_index_monthly
            cursor.execute('''
            INSERT OR REPLACE INTO city_price_index_monthly (
                city_id, city_name, month, new_home_mom, new_home_yoy,
                resale_home_mom, resale_home_yoy, source, source_url,
                collected_at, data_status, confidence_score, is_score_eligible, methodology_note
            ) VALUES (?, ?, ?, ?, ?, ?, ?, 'NBS_70CITY', 'https://www.stats.gov.cn/sj/zxfb/',
                      datetime('now'), 'official', 99, 1, 'NBS 70城住宅销售价格指数官方数据')
            ''', (city_id, city_name, month, new_home_mom, new_home_yoy, resale_home_mom, resale_home_yoy))
            
            # Log data quality
            cursor.execute('''
            INSERT INTO data_quality_log (city_id, metric_name, period, source, value_status, confidence_score,
                                          issue_reason, collected_at, data_status, is_score_eligible, methodology_note)
            VALUES (?, 'price_index', ?, 'NBS_70CITY', 'official', 99, 'CSV Import', datetime('now'),
                    'official', 1, 'NBS官方数据')
            ''', (city_id, month))
            
            rows_imported += 1
    
    conn.commit()
    print(f'Imported {rows_imported} NBS price index rows from CSV for 16 new cities.')
    return rows_imported
